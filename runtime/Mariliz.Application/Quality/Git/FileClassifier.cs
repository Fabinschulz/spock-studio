using System.Text.RegularExpressions;

namespace Mariliz.Application.Quality.Git;

/// <summary>Distingue o que não se revisa linha a linha (gerado, de terceiros) e o que é teste, só pelo caminho e pelo cabeçalho.</summary>
public static partial class FileClassifier
{
    private static readonly string[] ThirdPartyFolders = ["node_modules/", "vendor/", "third_party/", "third-party/", "Pods/", ".yarn/", "bower_components/"];
    private static readonly string[] GeneratedFolders = ["bin/", "obj/", "dist/", "build/", "target/", ".next/", "out/", "coverage/", "__pycache__/", ".turbo/"];

    private static readonly string[] LockFiles =
    [
        "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "Cargo.lock", "poetry.lock", "packages.lock.json", "composer.lock", "Gemfile.lock",
        "go.sum", "uv.lock", "requirements.lock", "bun.lockb", "npm-shrinkwrap.json"
    ];

    public static bool IsLockFile(string path) => LockFiles.Contains(Name(path), StringComparer.OrdinalIgnoreCase);

    public static string? SkipReason(ChangedFile file)
    {
        var path = file.Path.Replace('\\', '/');
        if (InFolder(path, ThirdPartyFolders)) return SkipReasons.ThirdParty;
        if (InFolder(path, GeneratedFolders) || IsLockFile(path) || GeneratedName().IsMatch(Name(path))) return SkipReasons.Generated;
        // Cabeçalho de gerador nas primeiras linhas que o diff mostra.
        if (file.Status == FileStatuses.Added || file.Status == FileStatuses.Untracked)
        {
            var head = string.Join('\n', file.AddedLines.Take(8).Select(line => line.Text));
            if (GeneratedHeader().IsMatch(head)) return SkipReasons.Generated;
        }
        return null;
    }

    public static bool IsTestPath(string path)
    {
        var normalized = path.Replace('\\', '/');
        return TestName().IsMatch(Name(normalized)) || TestFolder().IsMatch(normalized);
    }

    // Dados de exemplo para teste ou avaliação: o que parece segredo ali costuma ser inventado.
    public static bool IsFixturePath(string path) => FixtureFolder().IsMatch(path.Replace('\\', '/'));

    public static string Name(string path) => path[(path.LastIndexOf('/') + 1)..];

    private static bool InFolder(string path, string[] folders) =>
        folders.Any(folder => path.StartsWith(folder, StringComparison.OrdinalIgnoreCase) || path.Contains("/" + folder, StringComparison.OrdinalIgnoreCase));

    [GeneratedRegex(@"(\.min\.(js|css)|\.g\.cs|\.g\.i\.cs|\.designer\.cs|\.generated\.[a-z]+|\.pb\.go|_pb2\.py|\.snap)$", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedName();

    [GeneratedRegex(@"<auto-generated|@generated|Code generated by|DO NOT EDIT", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedHeader();

    [GeneratedRegex(@"(Tests?\.cs|Spec\.cs|\.(test|spec)\.[cm]?[jt]sx?|_test\.(go|py|rb)|^test_.*\.py|Test\.java|Tests\.java|_spec\.rb)$", RegexOptions.IgnoreCase)]
    private static partial Regex TestName();

    [GeneratedRegex(@"(^|/)(tests?|__tests__|spec|e2e)/", RegexOptions.IgnoreCase)]
    private static partial Regex TestFolder();

    [GeneratedRegex(@"(^|/)(fixtures?|__fixtures__|datasets?|testdata|__mocks__|mocks?|samples?)/", RegexOptions.IgnoreCase)]
    private static partial Regex FixtureFolder();
}
